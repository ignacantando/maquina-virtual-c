MOV [8],5        ;  [8]=5
OTRO: MOV EDX,DS ;  EDX-->[0]
MOV CL,1         ; CL=1
MOV CH,4         ;  CH=4
MOV AL,%1        ;  AL=1
SYS %1           ; LEE
CMP [0],0        ;  COMPARA SI ES 0 SALTA A FINCON
JZ FINCON       
CMP [0],1        ; COMPARA Y SI ES UNO PASA A FINCON SINO SALE 
JNZ SALE
FINCON: MUL [0],[4] ;MULTIPLICA LO LEIDO POR [4]
ADD [8],[0]         ;AGREGA EN 0 LO MULTIPLICADO ANTERIORMENTE
MUL [4],2           ;MULTIPLICA LO QUE ESTA EN [4]*2
JMP OTRO            ;VUELVE ARRIBA
SALE: MOV EDX,DS    ;IMPRIME
ADD EDX,8
MOV CL,1
MOV CH,4
MOV AL,%1
SYS %2
STOP
